"""Assemble the IQ Option scripts from the shared sources in src/.

    python build.py          write NextMinuteSignal.lua, NextMinuteScoreboard.lua and
                             extension/src/lua-scripts.js (both scripts, for the extension)
    python build.py --check  exit 1 if a built file is missing or out of date
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")

OUTPUTS = {
    "NextMinuteSignal.lua": ("signal_head.lua", "core.lua", "signal_tail.lua"),
    "NextMinuteScoreboard.lua": ("scoreboard_head.lua", "core.lua", "scoreboard_tail.lua"),
}
# The extension writes these scripts, with the learned settings filled in, into the user's account.
EXTENSION_SCRIPTS = os.path.join("extension", "src", "lua-scripts.js")
EXTENSION_KEYS = {"NextMinuteSignal.lua": "signal", "NextMinuteScoreboard.lua": "scoreboard"}


def render(parts: tuple[str, ...]) -> str:
    chunks = []
    for name in parts:
        with open(os.path.join(SRC, name), encoding="utf-8") as handle:
            chunks.append(handle.read().strip("\n") + "\n")
    text = "\n".join(chunks)
    text.encode("ascii")  # the traderoom editor gets plain ASCII only
    return text


def render_extension(scripts: dict[str, str]) -> str:
    body = ",\n".join(f"    {EXTENSION_KEYS[name]}: {json.dumps(text)}" for name, text in scripts.items())
    return (
        "// Generated by build.py from src/*.lua: do not edit. The chart scripts, so the extension can\n"
        "// write them (with the learned settings) into the user's account.\n"
        "(function (root) {\n"
        "  'use strict';\n"
        "  const scripts = {\n" + body + ",\n  };\n"
        "  if (typeof module === 'object' && module.exports) module.exports = scripts;\n"
        "  else root.NMLuaScripts = scripts;\n"
        "})(typeof self !== 'undefined' ? self : this);\n"
    )


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    texts = {output: render(parts) for output, parts in OUTPUTS.items()}
    files = dict(texts)
    files[EXTENSION_SCRIPTS] = render_extension(texts)
    for output, text in files.items():
        path = os.path.join(HERE, output)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as handle:
                current = handle.read()
        if current == text:
            continue
        if check:
            stale.append(output)
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            print(f"built {output}")
    if stale:
        print("out of date: " + ", ".join(stale) + " (run: python build.py)")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
